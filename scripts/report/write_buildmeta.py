"""Write reports/latex/buildmeta.tex with version, commit SHA and date.

Run via `make report` before latexmk. Never fails the build: on any
error it writes dev fallbacks so main.tex \\providecommand defaults win.
"""

from __future__ import annotations

import datetime
import subprocess
import sys
import tomllib
from pathlib import Path

REPORTS_DIR = Path(__file__).resolve().parent.parent.parent / "reports"


def _version() -> str:
    try:
        with open("pyproject.toml", "rb") as fh:
            return str(tomllib.load(fh)["project"]["version"])
    except (OSError, KeyError):
        return "0.0.0-dev"


def _commit() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip() or "dev"
    except (OSError, subprocess.CalledProcessError):
        return "dev"


def main() -> int:
    out_file = REPORTS_DIR / "latex" / "buildmeta.tex"
    date = datetime.datetime.now(tz=datetime.UTC).date().isoformat()
    content = (
        "% Generated by scripts/report/write_buildmeta.py (make report). "
        "Do not hand-edit.\n"
        f"\\newcommand{{\\ReportVersion}}{{{_version()}}}\n"
        f"\\newcommand{{\\ReportCommit}}{{{_commit()}}}\n"
        f"\\newcommand{{\\ReportDate}}{{{date}}}\n"
    )
    out_file.write_text(content, encoding="utf-8")
    print(f"wrote {out_file}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
